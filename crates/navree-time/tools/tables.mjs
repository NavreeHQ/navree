// Generates crates/navree-time/src/tables.rs: the legacy zone aliases and
// the zones of each country.
//
//   node crates/navree-time/tools/tables.mjs <chrono-tz>/tz/backward > crates/navree-time/src/tables.rs
//
// Sources:
// - Aliases: every `Link` of the IANA `backward` file shipped with the
//   chrono-tz crate, except the "Pre-2013 practice" section (those names are
//   still zone.tab locations, such as Europe/Oslo, and every PostgreSQL
//   accepts them). A `#= TARGET1` comment wins over the target, and chains
//   are followed, so Asia/Chungking ends at Asia/Shanghai.
// - Countries: the region-to-zone data of the ICU that Node.js ships
//   (`Intl.Locale#getTimeZones`), for current ISO 3166-1 codes only, each
//   zone normalized through the aliases. The first zone of a country is
//   its primary zone (PRIMARY below, else the first ICU lists).
//
// Run it again after upgrading chrono-tz; `cargo test -p navree-time`
// checks that every name in the tables is in chrono-tz.

import { readFileSync } from "node:fs";

const backwardPath = process.argv[2];
if (!backwardPath) {
  console.error("usage: node tables.mjs <path to tz/backward>");
  process.exit(2);
}

const text = readFileSync(backwardPath, "utf8");
const versionMatch = /^Release (\S+)/m.exec(
  readFileSync(backwardPath.replace(/backward$/, "NEWS"), "utf8"),
);

// Names that mean "no offset, ever": all become `UTC`.
const UTC_NAMES = [
  "Etc/GMT", "Etc/GMT+0", "Etc/GMT-0", "Etc/GMT0", "Etc/Greenwich", "Etc/UCT",
  "Etc/UTC", "Etc/Universal", "Etc/Zulu", "GMT", "GMT+0", "GMT-0", "GMT0",
  "Greenwich", "UCT", "Universal", "Zulu",
];

// ICU names whose IANA counterpart is not their `backward` target.
const ICU_RENAMES = {
  "America/Coral_Harbour": "America/Atikokan",
};

// The primary zone of countries with more than one.
const PRIMARY = {
  AR: "America/Argentina/Buenos_Aires",
  AU: "Australia/Sydney",
  BR: "America/Sao_Paulo",
  CA: "America/Toronto",
  CL: "America/Santiago",
  CY: "Asia/Nicosia",
  ES: "Europe/Madrid",
  FM: "Pacific/Pohnpei",
  GL: "America/Nuuk",
  KI: "Pacific/Tarawa",
  MH: "Pacific/Majuro",
  MN: "Asia/Ulaanbaatar",
  MX: "America/Mexico_City",
  PF: "Pacific/Tahiti",
  PG: "Pacific/Port_Moresby",
  PS: "Asia/Hebron",
  PT: "Europe/Lisbon",
  RU: "Europe/Moscow",
  UA: "Europe/Kyiv",
  US: "America/New_York",
  UZ: "Asia/Tashkent",
};

const links = new Map();
let section = "";
for (const line of text.split("\n")) {
  const heading = /^# (Pre-1993|Two-part names|Pre-2013 practice|Non-zone\.tab|Alternate names)/.exec(line);
  if (heading) section = heading[1];
  const m = /^Link\s+(\S+)\s+(\S+)(?:\s+#=\s+(\S+))?/.exec(line);
  if (!m) continue;
  const [, target, name, target1] = m;
  if (section.startsWith("Pre-2013 practice")) continue;
  links.set(name, target1 ?? target);
}

function canonical(name) {
  if (UTC_NAMES.includes(name)) return "UTC";
  if (ICU_RENAMES[name]) return ICU_RENAMES[name];
  const seen = new Set();
  let current = name;
  while (links.has(current) && !seen.has(current)) {
    seen.add(current);
    current = links.get(current);
  }
  return UTC_NAMES.includes(current) ? "UTC" : current;
}

const aliases = [...new Set([...links.keys(), ...UTC_NAMES])]
  .filter((name) => name !== "UTC")
  .map((name) => [name, canonical(name)])
  .filter(([name, target]) => name !== target)
  .sort(([a], [b]) => (a.toLowerCase() < b.toLowerCase() ? -1 : a.toLowerCase() > b.toLowerCase() ? 1 : 0));

const LETTERS = "ABCDEFGHIJKLMNOPQRSTUVWXYZ";
const regionNames = new Intl.DisplayNames(["en"], { type: "region" });
const countries = [];
for (const a of LETTERS) {
  for (const b of LETTERS) {
    const code = a + b;
    let zones;
    try {
      if (Intl.getCanonicalLocales(`und-${code}`)[0] !== `und-${code}`) continue;
      if (regionNames.of(code) === code) continue;
      zones = new Intl.Locale(`und-${code}`).getTimeZones();
    } catch {
      continue;
    }
    if (!zones || zones.length === 0) continue;
    let list = [...new Set(zones.map(canonical))];
    const primary = PRIMARY[code];
    if (primary) {
      if (!list.includes(primary)) throw new Error(`${code}: ${primary} is not among ${list}`);
      list = [primary, ...list.filter((z) => z !== primary)];
    }
    countries.push([code, list]);
  }
}
for (const code of Object.keys(PRIMARY)) {
  if (!countries.some(([c]) => c === code)) throw new Error(`no zones for ${code}`);
}

const out = [];
out.push("//! Generated by `tools/tables.mjs`; do not edit by hand.");
out.push("//!");
out.push(`//! Aliases from the IANA \`backward\` file of tzdata ${versionMatch ? versionMatch[1] : "?"}`);
out.push("//! (bundled with chrono-tz); countries from the ICU region data of");
out.push(`//! Node.js ${process.version}.`);
out.push("");
out.push("/// The tz database release the tables (and chrono-tz) were built from.");
out.push(`pub(crate) const TZDATA_VERSION: &str = "${versionMatch ? versionMatch[1] : "unknown"}";`);
out.push("");
out.push("/// Legacy and alternate names, with the current name each stands for,");
out.push("/// sorted by the lower-cased legacy name.");
out.push("#[rustfmt::skip]");
out.push("pub(crate) const ALIASES: &[(&str, &str)] = &[");
for (const [name, target] of aliases) out.push(`    ("${name}", "${target}"),`);
out.push("];");
out.push("");
out.push("/// ISO 3166-1 alpha-2 codes with their zones, primary zone first, sorted");
out.push("/// by code.");
out.push("#[rustfmt::skip]");
out.push("pub(crate) const COUNTRY_ZONES: &[(&str, &[&str])] = &[");
for (const [code, list] of countries) {
  out.push(`    ("${code}", &[${list.map((z) => `"${z}"`).join(", ")}]),`);
}
out.push("];");
process.stdout.write(out.join("\n") + "\n");
