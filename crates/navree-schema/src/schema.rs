    /// Converts existing `table` into a hypertable: checks its keys (widening
    /// the primary key with the time column, or explaining what blocks it),
    /// then creates the hypertable with its dimensions and policies. On a
    /// database without TimescaleDB it adds the time index and reports a
    /// notice.
    pub async fn convert_to_hypertable(
        &self,
        table: &str,
        hypertable: impl Into<Hypertable>,
    ) -> SchemaResult {
        let hypertable = hypertable.into();
        let target = self.target().await?;
        let conn = self.connection(|| format!("converting `{table}` to a hypertable"))?;
        let state = inspect::key_state(conn, target.dialect(), table).await?;
        let compiled = timescale::plan_convert(table, &hypertable, &state, &self.context(&target))?;
        self.run(compiled).await
    }

    /// Runs `statement` on TimescaleDB; elsewhere reports `"{reason}: {skipped}"`.
    async fn timescale_statement(
        &self,
        table: &str,
        statement: String,
        skipped: String,
    ) -> SchemaResult {
        let target = self.target().await?;
        let compiled =
            timescale::policy_or_notice(table, statement, &skipped, &self.context(&target))?;
        self.run(compiled).await
    }

