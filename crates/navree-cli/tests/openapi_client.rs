//! `navree openapi:client`: the `schema.d.ts` written for an OpenAPI
//! document. The fixtures in `tests/fixtures/openapi/` are documents with
//! the file each should give; the client package and the SaaS kit ship files
//! that must be what the generator writes now.

use std::path::{Path, PathBuf};
use std::process::Command;

use navree_cli::clock::Timestamp;
use navree_cli::kits::Kit;
use navree_cli::names::AppName;
use navree_cli::new_app::{Database, NavreeSource, NewApp, Ui, create_app};
use navree_cli::openapi_client::{GenerateError, generate};

fn workspace() -> PathBuf {
    std::path::absolute(Path::new(env!("CARGO_MANIFEST_DIR")).join("..").join("..")).unwrap()
}

fn fixture(name: &str) -> String {
    let path = Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("tests")
        .join("fixtures")
        .join("openapi")
        .join(name);
    read(&path)
}

/// A file's text with Unix line ends, as a checkout on Windows may have
/// changed them.
fn read(path: &Path) -> String {
    std::fs::read_to_string(path)
        .unwrap_or_else(|e| panic!("{}: {e}", path.display()))
        .replace("\r\n", "\n")
}

/// Shows the first line two texts differ at, not both whole files.
fn assert_same(what: &str, expected: &str, actual: &str) {
    if expected == actual {
        return;
    }
    let line = expected
        .lines()
        .zip(actual.lines())
        .position(|(e, a)| e != a)
        .unwrap_or_else(|| expected.lines().count().min(actual.lines().count()));
    panic!(
        "{what} differs at line {}:\n  expected: {:?}\n  actual:   {:?}",
        line + 1,
        expected.lines().nth(line),
        actual.lines().nth(line)
    );
}

fn schema_of(document: &str) -> String {
    generate(document)
        .unwrap_or_else(|e| panic!("the document is refused: {e}"))
        .schema
}

#[test]
fn every_fixture_document_gives_its_file() {
    for name in ["schemas", "paths", "discriminators", "edge"] {
        let generated = schema_of(&fixture(&format!("{name}.json")));
        assert_same(name, &fixture(&format!("{name}.d.ts")), &generated);
    }
}

