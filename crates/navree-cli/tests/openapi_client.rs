//! `navree openapi:client`: the `schema.d.ts` written for an OpenAPI
//! document. The fixtures in `tests/fixtures/openapi/` are documents with
//! the file each should give; the front ends in this repository and the SaaS
//! kit ship files that must be what the generator writes now.

use std::path::{Path, PathBuf};
use std::process::Command;

use navree_cli::clock::Timestamp;
use navree_cli::kits::Kit;
use navree_cli::names::AppName;
use navree_cli::new_app::{Database, NavreeSource, NewApp, Ui, create_app};
use navree_cli::openapi_client::{GenerateError, generate};

fn workspace() -> PathBuf {
    std::path::absolute(Path::new(env!("CARGO_MANIFEST_DIR")).join("..").join("..")).unwrap()
}

fn fixture(name: &str) -> String {
    let path = Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("tests")
        .join("fixtures")
        .join("openapi")
        .join(name);
    read(&path)
}

/// A file's text with Unix line ends, as a checkout on Windows may have
/// changed them.
fn read(path: &Path) -> String {
    std::fs::read_to_string(path)
        .unwrap_or_else(|e| panic!("{}: {e}", path.display()))
        .replace("\r\n", "\n")
}

/// Shows the first line two texts differ at, not both whole files.
fn assert_same(what: &str, expected: &str, actual: &str) {
    if expected == actual {
        return;
    }
    let line = expected
        .lines()
        .zip(actual.lines())
        .position(|(e, a)| e != a)
        .unwrap_or_else(|| expected.lines().count().min(actual.lines().count()));
    panic!(
        "{what} differs at line {}:\n  expected: {:?}\n  actual:   {:?}",
        line + 1,
        expected.lines().nth(line),
        actual.lines().nth(line)
    );
}

fn schema_of(document: &str) -> String {
    generate(document)
        .unwrap_or_else(|e| panic!("the document is refused: {e}"))
        .schema
}

#[test]
fn every_fixture_document_gives_its_file() {
    for name in ["schemas", "paths", "discriminators", "edge"] {
        let generated = schema_of(&fixture(&format!("{name}.json")));
        assert_same(name, &fixture(&format!("{name}.d.ts")), &generated);
    }
}

#[test]
fn the_front_ends_and_the_client_package_ship_what_the_generator_writes() {
    let root = workspace();
    for (document, schema) in [
        (
            "apps/crm-web/openapi.json",
            "apps/crm-web/src/lib/api/schema.d.ts",
        ),
        (
            "apps/crm-nuxt/openapi.json",
            "apps/crm-nuxt/app/lib/api/schema.d.ts",
        ),
        (
            "packages/js/client/test/fixtures/openapi.json",
            "packages/js/client/test/fixtures/schema.d.ts",
        ),
    ] {
        let generated = schema_of(&read(&root.join(document)));
        assert_same(schema, &read(&root.join(schema)), &generated);
    }
}

#[test]
fn the_saas_kit_ships_what_the_generator_writes() {
    let dir = tempfile::Builder::new()
        .prefix("navree-test-")
        .tempdir()
        .unwrap();
    let app = NewApp {
        name: AppName::parse("acme").unwrap(),
        ui: Ui::None,
        kit: Some(Kit::Saas),
        database: Database::default(),
        navree: NavreeSource::Path(PathBuf::from("/opt/navree/crates/navree")),
    };
    let created = create_app(dir.path(), &app, Timestamp::from_unix(1_792_938_605)).unwrap();
    let generated = schema_of(&read(&created.join("openapi.json")));
    assert_same(
        "web/lib/api/schema.d.ts",
        &read(&created.join("web/lib/api/schema.d.ts")),
        &generated,
    );
}

#[test]
fn declares_what_the_typed_client_takes() {
    let schema = schema_of(&fixture("paths.json"));
    for declaration in [
        "export interface paths {",
        "export interface webhooks {",
        "export interface components {",
        "export type $defs = Record<string, never>;",
        "export interface operations {",
    ] {
        assert!(schema.contains(declaration), "{declaration}");
    }
    let minimal = schema_of(r#"{"openapi":"3.1.0"}"#);
    assert_eq!(
        minimal,
        "/**\n * This file was auto-generated by navree openapi:client.\n * Do not make direct changes to the file.\n */\n\n\
export type paths = Record<string, never>;\n\
export type webhooks = Record<string, never>;\n\
export interface components {\n    schemas: never;\n    responses: never;\n    parameters: never;\n    requestBodies: never;\n    headers: never;\n    pathItems: never;\n}\n\
export type $defs = Record<string, never>;\n\
export type operations = Record<string, never>;\n"
    );
}

#[test]
fn refuses_documents_it_cannot_read() {
    let refused = |document: &str| generate(document).expect_err(document).to_string();
    assert!(refused("not json").contains("invalid JSON"));
    assert!(refused("[]").contains("expected `openapi: 3.x`"));
    assert!(refused(r#"{"info":{}}"#).contains("expected `openapi: 3.x`"));
    assert!(refused(r#"{"swagger":"2.0"}"#).contains("Swagger"));
    assert!(refused(r#"{"openapi":"4.0.0"}"#).contains("Unsupported OpenAPI version: 4.0.0"));
    assert!(refused(r#"{"openapi":3.1}"#).contains("should be a string"));
    // References stay inside the document and lead somewhere.
    assert!(
        refused(
            r##"{"openapi":"3.1.0","components":{"schemas":{"A":{"$ref":"#/components/schemas/B"}}}}"##
        )
        .contains("Can't resolve $ref \"#/components/schemas/B\"")
    );
    assert!(
        refused(r#"{"openapi":"3.1.0","components":{"schemas":{"A":{"$ref":"other.json#/B"}}}}"#)
            .contains("only references inside the document")
    );
    assert!(
        refused(
            r##"{"openapi":"3.1.0","components":{"schemas":{"A":{"$ref":"#/components/schemas/B"},"B":{"$ref":"#/components/schemas/A"}}}}"##
        )
        .contains("circular")
    );
    // An operation id names one operation.
    assert!(
        refused(
            r#"{"openapi":"3.1.0","paths":{"/a":{"get":{"operationId":"x"}},"/b":{"get":{"operationId":"x"}}}}"#
        )
        .contains("unique `operationId`")
    );
    // Something where a schema belongs.
    assert!(
        refused(r#"{"openapi":"3.1.0","components":{"schemas":{"A":5}}}"#)
            .contains("Expected SchemaObject")
    );
    assert!(
        refused(r#"{"openapi":"3.1.0","components":{"schemas":{"A":{"properties":{"a":5}}}}}"#)
            .contains("invalid property a")
    );
}

#[test]
fn warns_of_a_reference_that_leads_nowhere_and_goes_on() {
    // A discriminator mapped to a name the document does not have.
    let document = r##"{"openapi":"3.1.0","components":{"schemas":{
        "Pet":{"oneOf":[{"$ref":"#/components/schemas/Cat"}],"discriminator":{"propertyName":"kind","mapping":{"cat":"Cat"}}},
        "Cat":{"type":"object"}}}}"##;
    let generated = generate(document).unwrap();
    assert!(
        generated
            .schema
            .contains("Pet: components[\"schemas\"][\"Cat\"];")
    );
    assert_eq!(generated.warnings.len(), 1, "{:?}", generated.warnings);
    assert!(generated.warnings[0].contains("Discriminator mapping"));

    // A reference to a schema that is `false`: nothing to follow.
    let document = r##"{"openapi":"3.1.0","components":{"schemas":{
        "A":{"required":["x"],"allOf":[{"$ref":"#/components/schemas/F"}]},
        "F":false}}}"##;
    let generated = generate(document).unwrap();
    assert!(
        generated
            .schema
            .contains("A: components[\"schemas\"][\"F\"];")
    );
    assert_eq!(
        generated.warnings,
        ["Could not resolve $ref \"#/components/schemas/F\""]
    );
}

/// A schema nested `levels` deep in `shape`, where `{}` marks the place.
fn nested(shape: &str, levels: usize) -> String {
    let (open, close) = shape.split_once("{}").unwrap();
    format!(
        r#"{{"openapi":"3.1.0","components":{{"schemas":{{"A":{}{}{}}}}}}}"#,
        open.repeat(levels),
        r#"{"type":"string"}"#,
        close.repeat(levels)
    )
}

#[test]
fn a_deeply_nested_document_is_refused_not_overflowed() {
    // Nesting is capped and the work runs on a stack of its own, so what a
    // document can do with the stack does not depend on the caller's: call
    // from a thread with a small one.
    let handle = std::thread::Builder::new()
        .stack_size(256 * 1024)
        .spawn(|| {
            let shapes = [
                r#"{"type":"object","properties":{"a":{}}}"#,
                r#"{"allOf":[{}]}"#,
                r#"{"type":"array","items":{}}"#,
                r#"{"anyOf":[{}]}"#,
                r#"{"oneOf":[{},{"type":"string"}]}"#,
                r#"{"type":"object","additionalProperties":{}}"#,
                r#"{"type":["array","null"],"items":{}}"#,
            ];
            for shape in shapes {
                for levels in [10, 60, 62, 64, 100, 5_000, 200_000] {
                    // Either it generates or it is refused for its depth;
                    // it never takes the thread down.
                    match generate(&nested(shape, levels)) {
                        Ok(_) => {}
                        Err(GenerateError::NotJson(message)) => {
                            assert!(message.contains("nested too deeply"), "{message}");
                        }
                        Err(other) => panic!("{shape} x {levels}: {other}"),
                    }
                }
            }
        })
        .unwrap();
    handle.join().expect("no stack overflow");
}

#[test]
fn a_schema_that_lists_a_type_twice_is_not_written_without_bound() {
    // Each level lists `object` twice, so each level's children are written
    // twice: 40 levels would be 2^40 copies. The generator stops at its
    // limit instead, and says so.
    let document = nested(r#"{"type":["object","object"],"properties":{"a":{}}}"#, 40);
    let started = std::time::Instant::now();
    let error = generate(&document).unwrap_err().to_string();
    assert!(error.contains("asks for more than"), "{error}");
    assert!(
        started.elapsed() < std::time::Duration::from_secs(120),
        "{:?}",
        started.elapsed()
    );
    // A few levels are fine: 2^6 copies.
    assert!(
        generate(&nested(
            r#"{"type":["object","object"],"properties":{"a":{}}}"#,
            6
        ))
        .is_ok()
    );
}

#[test]
fn a_document_with_a_huge_number_of_keys_or_a_huge_number_is_read_in_proportion() {
    // Keys, not areas or counts the document claims, set the work.
    let mut schemas = String::new();
    for n in 0..20_000 {
        if n > 0 {
            schemas.push(',');
        }
        schemas.push_str(&format!(
            r#""S{n}":{{"type":"integer","maximum":1e999,"minItems":4294967295}}"#
        ));
    }
    let document = format!(r#"{{"openapi":"3.1.0","components":{{"schemas":{{{schemas}}}}}}}"#);
    let generated = schema_of(&document);
    assert_eq!(generated.matches(": number;").count(), 20_000);
    // An enum or an array that claims a size has only the values it lists.
    let schema = schema_of(
        r#"{"openapi":"3.1.0","components":{"schemas":{"A":{"type":"array","minItems":4294967295,"maxItems":4294967295,"items":{"type":"string"}}}}}"#,
    );
    assert!(schema.contains("A: string[];"), "{schema}");
}

#[test]
fn the_command_writes_the_schema_next_to_the_document() {
    let dir = tempfile::Builder::new()
        .prefix("navree-test-")
        .tempdir()
        .unwrap();
    std::fs::write(dir.path().join("openapi.json"), fixture("paths.json")).unwrap();
    // `--input` needs no app: the paths are the current directory's.
    let output = Command::new(env!("CARGO_BIN_EXE_navree"))
        .args([
            "openapi:client",
            "--input",
            "openapi.json",
            "--out",
            "web/lib/api",
        ])
        .current_dir(dir.path())
        .output()
        .expect("navree runs");
    assert!(
        output.status.success(),
        "{}",
        String::from_utf8_lossy(&output.stderr)
    );
    let stdout = String::from_utf8_lossy(&output.stdout);
    assert!(
        stdout.contains("wrote    web/lib/api/schema.d.ts"),
        "{stdout}"
    );
    assert_same(
        "the written schema",
        &fixture("paths.d.ts"),
        &read(&dir.path().join("web/lib/api/schema.d.ts")),
    );

    // A document it cannot read stops the command and names the file.
    std::fs::write(dir.path().join("bad.json"), r#"{"openapi":"4.0.0"}"#).unwrap();
    let output = Command::new(env!("CARGO_BIN_EXE_navree"))
        .args([
            "openapi:client",
            "--input",
            "bad.json",
            "--out",
            "web/lib/api",
        ])
        .current_dir(dir.path())
        .output()
        .expect("navree runs");
    assert!(!output.status.success());
    let stderr = String::from_utf8_lossy(&output.stderr);
    assert!(stderr.contains("bad.json"), "{stderr}");
    assert!(
        stderr.contains("Unsupported OpenAPI version: 4.0.0"),
        "{stderr}"
    );
}
