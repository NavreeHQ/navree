//! `navree openapi:client`: the typed client's schema for the front end.
//! The app exports its OpenAPI document (`openapi:export`), then the
//! generator in this module turns it into `schema.d.ts`, the `paths` type
//! that `createNavreeClient<paths>()` from `@navree/client` takes. It also
//! writes `components`, `operations` and `webhooks`, so
//! `components["schemas"]["User"]` names a schema.
//!
//! [`generate`] reads an OpenAPI 3.0 or 3.1 document (JSON, one file: every
//! `$ref` points inside it) and returns the declarations as text. It never
//! runs a program and reads no other file.

mod discriminators;
mod json;
mod refs;
mod transform;
mod ts;

use std::collections::HashSet;
use std::path::{Path, PathBuf};

use crate::forward::{Invocation, forward};
use json::Value;

/// The default output directory: the Next.js front end's API folder.
pub const DEFAULT_OUT: &str = "web/src/lib/api";

/// The largest document the generator reads.
pub const MAX_DOCUMENT_BYTES: u64 = 64 * 1024 * 1024;

/// The comment every generated file starts with.
const HEADER: &str = "/**\n * This file was auto-generated by navree openapi:client.\n * Do not make direct changes to the file.\n */\n\n";

/// What `navree openapi:client` does, in the app's directory.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ClientPlan {
    /// The OpenAPI document the schema is generated from.
    pub document: PathBuf,
    /// The generated `schema.d.ts`.
    pub schema: PathBuf,
    /// The export of the app's document (absent with `--input`), run before
    /// the schema is generated.
    pub export: Option<Invocation>,
}

/// The plan for `out` (relative to the app), from the app's own document or
/// from `input`.
pub fn plan(out: &Path, input: Option<&Path>) -> ClientPlan {
    let schema = out.join("schema.d.ts");
    let (document, export) = match input {
        Some(input) => (input.to_path_buf(), None),
        None => {
            let document = out.join("openapi.json");
            let export = forward("openapi:export", &[slash(&document)]);
            (document, Some(export))
        }
    };
    ClientPlan {
        document,
        schema,
        export,
    }
}

/// `path` with `/` separators, as tools on every platform accept it.
fn slash(path: &Path) -> String {
    path.to_string_lossy().replace('\\', "/")
}

/// A generated `schema.d.ts`.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Generated {
    /// The file's text.
    pub schema: String,
    /// Things in the document the generator could not follow (a `$ref` that
    /// leads nowhere, a discriminator whose schema cannot take a property).
    /// The schema is written without them.
    pub warnings: Vec<String>,
}

/// Why a schema could not be generated.
#[derive(Debug, Clone, PartialEq, Eq, thiserror::Error)]
#[non_exhaustive]
pub enum GenerateError {
    /// The document is larger than [`MAX_DOCUMENT_BYTES`].
    #[error("the OpenAPI document is larger than {MAX_DOCUMENT_BYTES} bytes")]
    TooLarge,
    /// The document is not JSON.
    #[error("{0}")]
    NotJson(String),
    /// The document is JSON but not an OpenAPI 3 document the generator can
    /// read.
    #[error("{0}")]
    Unsupported(String),
}

/// The `schema.d.ts` for an OpenAPI document.
pub fn generate(document: &str) -> Result<Generated, GenerateError> {
    if u64::try_from(document.len()).map_or(true, |len| len > MAX_DOCUMENT_BYTES) {
        return Err(GenerateError::TooLarge);
    }
    // The document nests no deeper than `json::MAX_DEPTH`, so the work below
    // recurses a bounded number of times; it runs on a thread whose stack is
    // sized for that, whatever stack the caller has.
    std::thread::scope(|scope| {
        std::thread::Builder::new()
            .name("openapi-client".to_owned())
            .stack_size(STACK_BYTES)
            .spawn_scoped(scope, || generate_here(document))
            .map_err(|e| GenerateError::Unsupported(format!("cannot start the generator: {e}")))?
            .join()
            .map_err(|_| {
                GenerateError::Unsupported("the generator stopped unexpectedly".to_owned())
            })?
    })
}

/// The stack the generator's thread gets. It is address space until used.
const STACK_BYTES: usize = 64 * 1024 * 1024;

fn generate_here(document: &str) -> Result<Generated, GenerateError> {
    let document = json::parse(document).map_err(GenerateError::NotJson)?;
    check(&document).map_err(GenerateError::Unsupported)?;
    let declarations = transform::declarations(document).map_err(GenerateError::Unsupported)?;
    Ok(Generated {
        schema: ts::print_file(HEADER, &declarations.statements),
        warnings: declarations.warnings,
    })
}

/// The methods of a path item.
const METHODS: [&str; 8] = [
    "get", "put", "post", "delete", "options", "head", "patch", "trace",
];

/// Checks what the generator relies on: an OpenAPI 3 version, references
/// that point inside the document and lead somewhere, and operation ids that
/// are unique.
fn check(document: &Value) -> Result<(), String> {
    let Some(root) = document.as_object() else {
        return Err("Unsupported schema format, expected `openapi: 3.x`".to_owned());
    };
    if root.get("swagger").is_some_and(Value::truthy) {
        return Err("Unsupported Swagger version: 2.x. Use OpenAPI 3.x instead.".to_owned());
    }
    let version = root.get("openapi").filter(|version| version.truthy());
    let number = version.map_or(f64::NAN, |version| parse_float(&version.js_string()));
    if version.is_none() || number.is_nan() || !(3.0..4.0).contains(&number) {
        return Err(match version {
            Some(version) => format!("Unsupported OpenAPI version: {}", version.js_string()),
            None => "Unsupported schema format, expected `openapi: 3.x`".to_owned(),
        });
    }
    if let Some(version) = version
        && version.as_str().is_none()
    {
        let kind = match version {
            Value::Num(_) => "number",
            Value::Bool(_) => "boolean",
            _ => "object",
        };
        return Err(format!(
            "Invalid OpenAPI version: should be a string but got \"{kind}\""
        ));
    }
    check_refs(document, document)?;
    let mut seen: HashSet<&str> = HashSet::new();
    for section in ["paths", "webhooks"] {
        let items = root.get(section).and_then(Value::as_object);
        for (_, item) in items.map(json::Object::js_entries).unwrap_or_default() {
            for method in METHODS {
                let Some(id) = item
                    .get(method)
                    .and_then(|operation| operation.get("operationId"))
                    .and_then(Value::as_str)
                    .filter(|id| !id.is_empty())
                else {
                    continue;
                };
                if !seen.insert(id) {
                    return Err(format!(
                        "Every operation must have a unique `operationId`: `{id}` is used twice"
                    ));
                }
            }
        }
    }
    Ok(())
}

/// Every `$ref` in the document leads somewhere inside it.
fn check_refs(root: &Value, node: &Value) -> Result<(), String> {
    match node {
        Value::Arr(items) => items.iter().try_for_each(|item| check_refs(root, item)),
        Value::Obj(object) => {
            if let Some(reference) = object.get("$ref").and_then(Value::as_str) {
                if !reference.starts_with('#') {
                    return Err(format!(
                        "Can't resolve $ref \"{reference}\": only references inside the document are supported; bundle the document into one file first"
                    ));
                }
                // Follow the reference, and any reference it leads to, to the end.
                let mut seen = vec![reference];
                let mut next = reference;
                loop {
                    let found = refs::parse_ref(next)
                        .iter()
                        .try_fold(root, |at, key| at.get(key));
                    let Some(found) = found else {
                        return Err(format!("Can't resolve $ref \"{next}\""));
                    };
                    match found.get("$ref").and_then(Value::as_str) {
                        Some(again) if again.starts_with('#') => {
                            if seen.len() > discriminators::MAX_HOPS {
                                return Err(format!(
                                    "Can't resolve $ref \"{reference}\": it leads through more than {} references",
                                    discriminators::MAX_HOPS
                                ));
                            }
                            if seen.contains(&again) {
                                return Err(format!(
                                    "Self-referencing circular pointer: \"{reference}\""
                                ));
                            }
                            seen.push(again);
                            next = again;
                        }
                        _ => break,
                    }
                }
            }
            object
                .js_entries()
                .into_iter()
                .try_for_each(|(_, value)| check_refs(root, value))
        }
        _ => Ok(()),
    }
}

/// JavaScript's `parseFloat`: the number a string starts with, or NaN.
fn parse_float(text: &str) -> f64 {
    let text = text.trim_start();
    let bytes = text.as_bytes();
    let mut end = 0;
    if matches!(bytes.first(), Some(b'+' | b'-')) {
        end += 1;
    }
    let digits_from = end;
    while bytes.get(end).is_some_and(u8::is_ascii_digit) {
        end += 1;
    }
    let mut digits = end - digits_from;
    if bytes.get(end) == Some(&b'.') {
        let point = end;
        end += 1;
        let fraction_from = end;
        while bytes.get(end).is_some_and(u8::is_ascii_digit) {
            end += 1;
        }
        digits += end - fraction_from;
        if end == fraction_from && digits == 0 {
            end = point;
        }
    }
    if digits == 0 {
        return f64::NAN;
    }
    if matches!(bytes.get(end), Some(b'e' | b'E')) {
        let mut exponent = end + 1;
        if matches!(bytes.get(exponent), Some(b'+' | b'-')) {
            exponent += 1;
        }
        let exponent_digits = exponent;
        while bytes.get(exponent).is_some_and(u8::is_ascii_digit) {
            exponent += 1;
        }
        if exponent > exponent_digits {
            end = exponent;
        }
    }
    text.get(..end)
        .and_then(|number| number.parse::<f64>().ok())
        .unwrap_or(f64::NAN)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn exports_the_document_then_generates_the_schema() {
        let plan = plan(Path::new("web/src/lib/api"), None);
        assert_eq!(
            plan.document,
            Path::new("web/src/lib/api").join("openapi.json")
        );
        assert_eq!(
            plan.schema,
            Path::new("web/src/lib/api").join("schema.d.ts")
        );
        let export = plan.export.expect("the app's document is exported");
        assert_eq!(export.program, "cargo");
        assert_eq!(
            export.args,
            [
                "run",
                "--quiet",
                "--",
                "openapi:export",
                "web/src/lib/api/openapi.json"
            ]
        );
    }

    #[test]
    fn generates_from_a_given_document_without_exporting() {
        let plan = plan(
            Path::new("web/app/lib/api"),
            Some(Path::new("openapi.json")),
        );
        assert_eq!(plan.document, Path::new("openapi.json"));
        assert_eq!(plan.export, None);
        assert_eq!(
            plan.schema,
            Path::new("web/app/lib/api").join("schema.d.ts")
        );
    }

    #[test]
    fn reads_the_leading_number_of_a_version() {
        assert_eq!(parse_float("3.1.0"), 3.1);
        assert_eq!(parse_float("  3"), 3.0);
        assert_eq!(parse_float("3e0x"), 3.0);
        assert_eq!(parse_float(".5"), 0.5);
        assert!(parse_float("v3").is_nan());
        assert!(parse_float(".").is_nan());
        assert!(parse_float("").is_nan());
    }
}
