// Reads the pinned flag-icons package, with CLDR's English names, into the flags
// the toolkit ships and writes src/flags/data.rs.

import { cleanFlag, rustRaw } from "./svg.mjs";
import { constName } from "./lucide.mjs";

/** Flags of bodies rather than places. */
const ORGANISATIONS = new Set(["eu", "un", "asean", "arab", "cefta", "eac", "pc"]);

/** Kosovo has no ISO 3166-1 code but a universal one (XK), and people pick it as a country. */
const COUNTRY_BESIDES_ISO = new Set(["xk"]);

/** The flag-icons code that is not ISO 3166-1 alpha-2, and the CLDR territory that names exactly that place. */
const CLDR_TERRITORY = { "sh-ac": "AC", "sh-ta": "TA", ic: "IC", cp: "CP", dg: "DG" };

/** The flag-icons code and the CLDR subdivision (ISO 3166-2, lower case, no hyphen). */
const CLDR_SUBDIVISION = {
  "gb-eng": "gbeng", "gb-nir": "gbnir", "gb-sct": "gbsct", "gb-wls": "gbwls",
  "es-ct": "esct", "es-ga": "esga", "es-pv": "espv",
};

/** Not the artwork of a place: flag-icons' "unknown" flag, which the toolkit replaces with its own placeholder. */
const SKIPPED = new Set(["xx"]);

function readJson(files, path) {
  const bytes = files.get(path);
  if (!bytes) throw new Error(`no ${path} in the package`);
  return JSON.parse(bytes.toString("utf8"));
}

/**
 * @param {Map<string, Buffer>} flagFiles flag-icons
 * @param {Map<string, Buffer>} territoryFiles cldr-localenames-full
 * @param {Map<string, Buffer>} subdivisionFiles cldr-subdivisions-full
 */
export function readFlags(flagFiles, territoryFiles, subdivisionFiles) {
  const version = readJson(flagFiles, "package.json").version;
  const list = readJson(flagFiles, "country.json");
  const territories = readJson(territoryFiles, "main/en/territories.json").main.en.localeDisplayNames.territories;
  const subdivisions = readJson(subdivisionFiles, "subdivisions/en/en.json").main?.en?.localeDisplayNames?.subdivisions
    ?? readJson(subdivisionFiles, "subdivisions/en/en.json").subdivisions.localeDisplayNames.subdivisions;
  const cldrVersion = readJson(territoryFiles, "package.json").version;

  const flags = [];
  const fromCldr = [];
  const fromFlagIcons = [];
  const flattened = [];
  for (const entry of list) {
    if (SKIPPED.has(entry.code)) continue;
    const code = entry.code.toUpperCase();
    if (!/^[A-Z]{2}(-[A-Z]{2,3})?$|^[A-Z]{3,5}$/.test(code)) throw new Error(`flags: odd code ${entry.code}`);

    let name = null;
    if (entry.iso || COUNTRY_BESIDES_ISO.has(entry.code) || entry.code === "eu" || entry.code === "un") {
      name = territories[code] ?? null;
    }
    if (!name && CLDR_TERRITORY[entry.code]) name = territories[CLDR_TERRITORY[entry.code]] ?? null;
    if (!name && CLDR_SUBDIVISION[entry.code]) name = subdivisions[CLDR_SUBDIVISION[entry.code]] ?? null;
    if (name) fromCldr.push(code);
    else {
      name = entry.name;
      fromFlagIcons.push(code);
    }
    if (!name || /["\\]/.test(name)) throw new Error(`flags: ${code} has no usable name`);

    const kind = ORGANISATIONS.has(entry.code)
      ? "Organisation"
      : entry.iso || COUNTRY_BESIDES_ISO.has(entry.code)
        ? "Country"
        : "Region";

    const rect = cleanFlag(text(flagFiles, entry.flag_4x3), `${entry.flag_4x3}`, `f4-${entry.code}-`);
    const square = cleanFlag(text(flagFiles, entry.flag_1x1), `${entry.flag_1x1}`, `f1-${entry.code}-`);
    if (rect.gradients || square.gradients) flattened.push(entry.code.toUpperCase());
    if (rect.viewBox !== "0 0 640 480") throw new Error(`flags: ${entry.flag_4x3} has viewBox ${rect.viewBox}`);
    if (square.viewBox !== "0 0 512 512") throw new Error(`flags: ${entry.flag_1x1} has viewBox ${square.viewBox}`);
    flags.push({ code, name, kind, rect: rect.inner, square: square.inner });
  }
  flags.sort((a, b) => (a.code < b.code ? -1 : a.code > b.code ? 1 : 0));
  const seen = new Set();
  for (const { code } of flags) {
    if (seen.has(code)) throw new Error(`flags: ${code} twice`);
    seen.add(code);
  }
  return { version, cldrVersion, flags, fromCldr, fromFlagIcons, flattened };
}

function text(files, path) {
  const bytes = files.get(path);
  if (!bytes) throw new Error(`flag-icons has no ${path}`);
  return bytes.toString("utf8");
}

/** The text of src/flags/data.rs. */
export function flagsRust({ version, cldrVersion, flags }) {
  const lines = [];
  lines.push(
    `//! Every flag, generated by \`runtime/icons.mjs\` from flag-icons ${version} (MIT),`,
    `//! with English names from Unicode CLDR ${cldrVersion} (Unicode-3.0). Do not edit by hand:`,
    "//! run `node crates/navree-ui/runtime/icons.mjs`. See THIRD_PARTY.md.",
    "",
    "use super::{CodeKind, CountryCode};",
    "",
  );
  for (const { code, name, kind, rect, square } of flags) {
    lines.push(
      `/// \`${code}\`: ${name}.`,
      `pub const ${constName(code)}: CountryCode = CountryCode::generated(`,
      `    "${code}",`,
      `    "${name}",`,
      `    CodeKind::${kind},`,
      `    ${rustRaw(rect)},`,
      `    ${rustRaw(square)},`,
      ");",
    );
  }
  lines.push(
    "",
    "/// Every flag, sorted by code. Naming this table in a binary puts every flag in that",
    "/// binary; an app that names single flags does not.",
    "pub const ALL: &[CountryCode] = &[",
    ...flags.map(({ code }) => `    ${constName(code)},`),
    "];",
    "",
  );
  return lines.join("\n");
}
