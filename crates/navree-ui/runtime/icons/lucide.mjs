// Reads a pinned lucide-static package into the icons the toolkit ships and
// writes src/icons/lucide.rs.

import { ATTRIBUTES, parse, rustRaw, write } from "./svg.mjs";

const SHAPES = new Set(["path", "circle", "rect", "line", "ellipse", "polyline", "polygon"]);
const NAME = /^[a-z][a-z0-9]*(-[a-z0-9]+)*$/;
/** Names the generated module defines itself. */
const RESERVED = new Set(["ALL", "RENAMED", "ICON", "SELF", "SUPER", "CRATE"]);

/** `trash-2` is `TRASH_2`. */
export function constName(name) {
  return name.toUpperCase().replace(/-/g, "_");
}

/** `{tag, attrs, children}` for each node of one icon. */
function elements(name, nodes) {
  return nodes.map(([tag, attrs]) => {
    if (!SHAPES.has(tag)) throw new Error(`lucide ${name}: <${tag}> is not a shape`);
    const list = Object.entries(attrs).map(([key, value]) => {
      if (!ATTRIBUTES.has(key)) throw new Error(`lucide ${name}: attribute ${key} is not one the toolkit keeps`);
      const text = String(value);
      if (!/^[A-Za-z0-9 .,+\-()#%_]*$/.test(text)) throw new Error(`lucide ${name}: ${key}=${JSON.stringify(text)} has odd characters`);
      return [key, text];
    });
    return { tag, attrs: list, children: [] };
  });
}

/** A drawing's identity, the same whatever order its attributes were written in. */
function signature(list) {
  return JSON.stringify(list.map((e) => [e.tag, [...e.attrs].sort(([a], [b]) => (a < b ? -1 : 1))]));
}

/**
 * @param {Map<string, Buffer>} files the package's files
 * @returns {{version: string, icons: {name: string, markup: string}[], renamed: [string, string][], tags: Record<string, string[]>}}
 */
export function readLucide(files) {
  const read = (path) => {
    const bytes = files.get(path);
    if (!bytes) throw new Error(`lucide-static has no ${path}`);
    return bytes.toString("utf8");
  };
  const version = JSON.parse(read("package.json")).version;
  const nodes = JSON.parse(read("icon-nodes.json"));
  const tags = JSON.parse(read("tags.json"));

  const icons = [];
  const bySignature = new Map();
  for (const name of Object.keys(nodes).sort()) {
    if (!NAME.test(name)) throw new Error(`lucide: odd icon name ${JSON.stringify(name)}`);
    if (RESERVED.has(constName(name))) throw new Error(`lucide: ${name} collides with a name the module defines`);
    const list = elements(name, nodes[name]);
    icons.push({ name, markup: list.map(write).join("") });
    const key = signature(list);
    if (!bySignature.has(key)) bySignature.set(key, []);
    bySignature.get(key).push(name);
  }

  // Old names are the package's SVG files that have no entry among the nodes;
  // each draws exactly what one current icon draws.
  const renamed = [];
  const known = new Set(icons.map((i) => i.name));
  for (const path of [...files.keys()].sort()) {
    const match = /^icons\/([^/]+)\.svg$/.exec(path);
    if (!match || known.has(match[1])) continue;
    const old = match[1];
    if (!NAME.test(old)) throw new Error(`lucide: odd old name ${JSON.stringify(old)}`);
    const root = parse(read(path), path);
    const list = root.children.map((child) => {
      if (!SHAPES.has(child.tag)) throw new Error(`${path}: <${child.tag}> is not a shape`);
      return { tag: child.tag, attrs: child.attrs, children: [] };
    });
    const targets = bySignature.get(signature(list)) ?? [];
    if (targets.length !== 1) {
      throw new Error(`lucide: the old name ${old} matches ${targets.length} current icons (${targets.join(", ")}), so its target is not certain`);
    }
    if (RESERVED.has(constName(old))) throw new Error(`lucide: ${old} collides with a name the module defines`);
    renamed.push([old, targets[0]]);
  }

  const cleanTags = {};
  for (const { name } of icons) {
    const list = tags[name];
    if (!Array.isArray(list)) throw new Error(`lucide: ${name} has no tags entry`);
    cleanTags[name] = [...new Set(list.map((t) => String(t).trim().toLowerCase()).filter(Boolean))];
  }
  return { version, icons, renamed, tags: cleanTags };
}

/** The text of src/icons/lucide.rs. */
export function lucideRust({ version, icons, renamed }) {
  const lines = [];
  lines.push(
    `//! Every Lucide icon, generated by \`runtime/icons.mjs\` from lucide-static ${version}.`,
    "//! Do not edit by hand: run `node crates/navree-ui/runtime/icons.mjs`. Lucide is under",
    "//! the ISC licence, with the MIT licence for icons derived from Feather: see",
    "//! THIRD_PARTY.md.",
    "",
    "use super::Icon;",
    "",
  );
  for (const { name, markup } of icons) {
    lines.push(`/// \`${name}\`.`, `pub const ${constName(name)}: Icon = Icon::new(${rustRaw(markup)});`);
  }
  lines.push("", "// Names Lucide has renamed. They still compile, with a warning that names the new icon.");
  for (const [old, current] of renamed) {
    lines.push(
      `/// \`${old}\`, now \`${current}\`.`,
      `#[deprecated(note = "Lucide renamed this icon: use ${constName(current)}")]`,
      `pub const ${constName(old)}: Icon = ${constName(current)};`,
    );
  }
  lines.push(
    "",
    "/// Every icon with its Lucide name, sorted by name. Naming this table in a binary",
    "/// puts every icon in that binary; an app that names single icons does not.",
    "pub const ALL: &[(&str, Icon)] = &[",
    ...icons.map(({ name }) => `    ("${name}", ${constName(name)}),`),
    "];",
    "",
    "/// Old names and the current names they became, sorted by old name.",
    "pub(super) const RENAMED: &[(&str, &str)] = &[",
    ...renamed.map(([old, current]) => `    ("${old}", "${current}"),`),
    "];",
    "",
  );
  return lines.join("\n");
}
