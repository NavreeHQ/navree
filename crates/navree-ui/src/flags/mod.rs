//! Flags: every country and the other places and bodies that have one.
//!
//! A flag is named by a [`CountryCode`], a small `Copy` value that holds the
//! code, its English name and the artwork. Each code is a constant, so an app's
//! binary holds the flags its code names and no others:
//!
//! - `flags::IN`: a constant. A code that does not exist does not compile.
//! - `flag!("IN")`: the code as a string, checked while the app compiles.
//! - [`CountryCode::parse`] and [`Flag::country`](crate::Flag::country): a code
//!   that arrives at run time. This is the one call that puts all of the flags
//!   into a binary.
//!
//! The set is [flag-icons](https://github.com/lipis/flag-icons) (MIT): the 249
//! ISO 3166-1 countries and Kosovo, the European Union and the United Nations,
//! the four nations of the United Kingdom, three regions of Spain, and a few
//! more. The artwork comes in two shapes, 4 by 3 and square; round flags are
//! the square art cropped. Names are English names from Unicode CLDR
//! (Unicode-3.0). See THIRD_PARTY.md.
//!
//! The artwork is generated by `runtime/icons.mjs`; ids inside it are made
//! unique per flag and shape, and there are no styles, links or scripts.

use core::cmp::Ordering;
use core::fmt;
use core::hash::{Hash, Hasher};
use core::str::FromStr;

use serde::{Deserialize, Deserializer, Serialize, Serializer};

use crate::icons::compare;

#[rustfmt::skip]
mod data;

pub use data::*;

/// What a [`CountryCode`] names.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
#[non_exhaustive]
pub enum CodeKind {
    /// A country: ISO 3166-1, and Kosovo (`XK`).
    Country,
    /// A place that is not a country: a nation of the United Kingdom, a region
    /// of Spain, an island group.
    Region,
    /// A body: the European Union, the United Nations, ASEAN and the like.
    Organisation,
}

/// The code of a flag: an ISO 3166-1 alpha-2 country code such as `AE`, or the
/// code of a region or body that has a flag, such as `EU` or `GB-SCT`.
///
/// It holds the flag's English name and artwork, so it is the same size as a few
/// pointers and needs no lookup to draw. Two codes are equal when their text is.
#[derive(Clone, Copy)]
pub struct CountryCode {
    code: &'static str,
    name: &'static str,
    kind: CodeKind,
    rect: &'static str,
    square: &'static str,
}

impl CountryCode {
    /// A code with its artwork. For the generated constants.
    pub(crate) const fn generated(
        code: &'static str,
        name: &'static str,
        kind: CodeKind,
        rect: &'static str,
        square: &'static str,
    ) -> Self {
        Self {
            code,
            name,
            kind,
            rect,
            square,
        }
    }

    /// The code in capitals: `AE`, `GB-SCT`.
    pub const fn as_str(self) -> &'static str {
        self.code
    }

    /// The English name from Unicode CLDR: `United Arab Emirates`.
    pub const fn name(self) -> &'static str {
        self.name
    }

    /// Whether this is a country, a region or a body.
    pub const fn kind(self) -> CodeKind {
        self.kind
    }

    /// The artwork for a 4 by 3 flag: shapes in a `0 0 640 480` box.
    pub const fn rect_shapes(self) -> &'static str {
        self.rect
    }

    /// The artwork for a square or round flag: shapes in a `0 0 512 512` box.
    pub const fn square_shapes(self) -> &'static str {
        self.square
    }

    /// The code written in `text`, in capitals or not, with `_` or `-` between
    /// the parts of `GB-SCT`. `None` when no flag has it.
    ///
    /// This is a `const fn`, and in a `const` it is checked while the app
    /// compiles: [`flag!`](crate::flag) does that. Called at run time it puts every
    /// flag into the binary, since the code could be any of them.
    pub const fn parse(text: &str) -> Option<CountryCode> {
        let wanted = text.as_bytes();
        if wanted.is_empty() || wanted.len() > MAX_CODE {
            return None;
        }
        let (mut low, mut high) = (0, ALL.len());
        while low < high {
            let mid = low + (high - low) / 2;
            match compare_code(wanted, ALL[mid].code.as_bytes()) {
                Ordering::Equal => return Some(ALL[mid]),
                Ordering::Less => high = mid,
                Ordering::Greater => low = mid + 1,
            }
        }
        None
    }

    /// The countries, in code order: every code whose [`kind`](Self::kind) is
    /// [`CodeKind::Country`]. A country picker starts here. This puts every flag
    /// into the binary.
    pub fn countries() -> impl Iterator<Item = CountryCode> {
        ALL.iter()
            .copied()
            .filter(|code| code.kind == CodeKind::Country)
    }
}

/// The longest code, `GB-SCT`, and the longest body, `ASEAN`, with room to spare.
const MAX_CODE: usize = 8;

/// Compares typed text (any case, `_` for `-`) with a code in capitals.
const fn compare_code(typed: &[u8], code: &[u8]) -> Ordering {
    let shortest = if typed.len() < code.len() {
        typed.len()
    } else {
        code.len()
    };
    let mut i = 0;
    while i < shortest {
        let mut a = typed[i];
        if a == b'_' {
            a = b'-';
        } else if a.is_ascii_lowercase() {
            a = a.to_ascii_uppercase();
        }
        let b = code[i];
        if a != b {
            return if a < b {
                Ordering::Less
            } else {
                Ordering::Greater
            };
        }
        i += 1;
    }
    if typed.len() == code.len() {
        Ordering::Equal
    } else if typed.len() < code.len() {
        Ordering::Less
    } else {
        Ordering::Greater
    }
}

impl PartialEq for CountryCode {
    fn eq(&self, other: &Self) -> bool {
        self.code == other.code
    }
}

impl Eq for CountryCode {}

impl Hash for CountryCode {
    fn hash<H: Hasher>(&self, state: &mut H) {
        self.code.hash(state);
    }
}

impl PartialOrd for CountryCode {
    fn partial_cmp(&self, other: &Self) -> Option<Ordering> {
        Some(self.cmp(other))
    }
}

impl Ord for CountryCode {
    fn cmp(&self, other: &Self) -> Ordering {
        compare(self.code, other.code)
    }
}

impl fmt::Debug for CountryCode {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "CountryCode({})", self.code)
    }
}

impl fmt::Display for CountryCode {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(self.code)
    }
}

/// The text was not the code of any flag.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct UnknownCode;

impl fmt::Display for UnknownCode {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str("no flag has this code")
    }
}

impl std::error::Error for UnknownCode {}

impl FromStr for CountryCode {
    type Err = UnknownCode;

    fn from_str(text: &str) -> Result<Self, Self::Err> {
        Self::parse(text).ok_or(UnknownCode)
    }
}

impl Serialize for CountryCode {
    fn serialize<S: Serializer>(&self, serializer: S) -> Result<S::Ok, S::Error> {
        serializer.serialize_str(self.code)
    }
}

impl<'de> Deserialize<'de> for CountryCode {
    fn deserialize<D: Deserializer<'de>>(deserializer: D) -> Result<Self, D::Error> {
        let text = std::borrow::Cow::<str>::deserialize(deserializer)?;
        Self::parse(&text).ok_or_else(|| {
            serde::de::Error::custom(format!("{:?} is not the code of a flag", text.as_ref()))
        })
    }
}

/// A flag by the code a person writes, checked while the app compiles.
///
/// ```
/// use navree_ui::{flag, flags};
///
/// let flag = flag!("in");
/// assert_eq!(flag.code(), Some(flags::IN));
/// ```
///
/// A code that no flag has stops the build and names the code:
///
/// ```compile_fail
/// let _ = navree_ui::flag!("AX1");
/// ```
///
/// Only the flag named goes into the binary.
#[macro_export]
macro_rules! flag {
    ($code:literal) => {
        $crate::Flag::new(
            const {
                match $crate::flags::CountryCode::parse($code) {
                    Some(code) => code,
                    None => panic!(concat!("no flag has the code ", $code)),
                }
            },
        )
    };
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_table_is_sorted_so_the_search_finds_every_flag() {
        for pair in ALL.windows(2) {
            assert_eq!(
                compare(pair[0].code, pair[1].code),
                Ordering::Less,
                "{} then {}",
                pair[0].code,
                pair[1].code
            );
        }
        for code in ALL {
            assert_eq!(CountryCode::parse(code.as_str()), Some(*code));
        }
    }

    #[test]
    fn every_iso_country_and_the_extra_places_are_there() {
        assert_eq!(CountryCode::countries().count(), 250);
        for code in [
            "AE", "US", "IN", "GB", "DE", "FR", "JP", "BR", "ZW", "AX", "XK",
        ] {
            let found = CountryCode::parse(code).expect(code);
            assert_eq!(found.kind(), CodeKind::Country, "{code}");
        }
        for code in ["EU", "UN", "ASEAN"] {
            assert_eq!(
                CountryCode::parse(code).expect(code).kind(),
                CodeKind::Organisation
            );
        }
        for code in [
            "GB-SCT", "GB-ENG", "GB-WLS", "GB-NIR", "ES-CT", "ES-GA", "ES-PV",
        ] {
            assert_eq!(
                CountryCode::parse(code).expect(code).kind(),
                CodeKind::Region
            );
        }
    }

    #[test]
    fn codes_read_in_any_case_and_with_an_underscore() {
        let expected = Some(GB_SCT);
        for text in ["GB-SCT", "gb-sct", "Gb-Sct", "gb_sct", "GB_SCT"] {
            assert_eq!(CountryCode::parse(text), expected, "{text}");
        }
        assert_eq!(CountryCode::parse("ae"), Some(AE));
        assert_eq!(CountryCode::parse("Ae"), Some(AE));
    }

    #[test]
    fn text_that_is_not_a_code_is_none_and_never_a_panic() {
        let long = "A".repeat(10_000);
        for text in [
            "", " ", "A", "AEX", "ZZ", "XX", "A E", " AE", "AE ", "AE\0", "ae-", "-ae", "ÆE", "🇦🇪",
            "gb--sct", "gb-sc", "gb-scts", &long,
        ] {
            assert_eq!(CountryCode::parse(text), None, "{text:.20?}");
        }
    }

    #[test]
    fn the_name_is_the_cldr_one() {
        assert_eq!(AE.name(), "United Arab Emirates");
        assert_eq!(TR.name(), "Türkiye");
        assert_eq!(CZ.name(), "Czechia");
        assert_eq!(GB_SCT.name(), "Scotland");
        assert_eq!(EU.name(), "European Union");
        assert_eq!(ES_CT.name(), "Catalonia");
        for code in ALL {
            assert!(!code.name().is_empty(), "{code}");
        }
    }

    #[test]
    fn a_code_prints_reads_and_serializes_as_its_text() {
        assert_eq!(AE.to_string(), "AE");
        assert_eq!("ae".parse::<CountryCode>(), Ok(AE));
        assert!("zz".parse::<CountryCode>().is_err());
        assert_eq!(serde_json::to_string(&GB_SCT).unwrap(), "\"GB-SCT\"");
        assert_eq!(
            serde_json::from_str::<CountryCode>("\"gb-sct\"").unwrap(),
            GB_SCT
        );
        assert!(serde_json::from_str::<CountryCode>("\"nope\"").is_err());
        assert!(serde_json::from_str::<CountryCode>("7").is_err());
    }

    #[test]
    fn codes_sort_and_hash_by_their_text() {
        let mut codes = vec![US, AE, GB_SCT, EU];
        codes.sort();
        assert_eq!(codes, vec![AE, EU, GB_SCT, US]);
        let set: std::collections::HashSet<_> = [AE, AE, US].into_iter().collect();
        assert_eq!(set.len(), 2);
    }
}
