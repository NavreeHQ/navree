/// The row for a language. English regions that write like British English
/// share its row.
pub(super) fn for_language(language: &str, region: Option<&str>) -> &'static LocaleData {
    match language {
        "en" => match region {
            None | Some("US" | "CA" | "PH" | "PR" | "VI" | "GU" | "AS") => &EN,
            Some(_) => &EN_GB,
        },
        "de" => &DE,
        "fr" => &FR,
        "es" => &ES,
        "it" => &IT,
        "pt" => &PT,
        "nl" => &NL,
        "sv" => &SV,
        "pl" => &PL,
        "ru" => &RU,
        "tr" => &TR,
        "ja" => &JA,
        "zh" => &ZH,
        "ko" => &KO,
        "ar" => &AR,
        "he" => &HE,
        "hi" => &HI,
        "id" => &ID,
        _ => &EN,
    }
}

/// The first day of the week in a region, from the CLDR's week data. A region the
/// table doesn't list starts on Monday, as the CLDR's default does.
pub(super) fn region_first_day(region: &str) -> Option<Weekday> {
    if region.len() != 2 {
        return None;
    }
    Some(match region {
        "MV" => Weekday::Fri,
        "AE" | "AF" | "BH" | "DJ" | "DZ" | "EG" | "IQ" | "IR" | "JO" | "KW" | "LY" | "OM"
        | "QA" | "SD" | "SY" => Weekday::Sat,
        "AG" | "AS" | "BD" | "BR" | "BS" | "BT" | "BW" | "BZ" | "CA" | "CO" | "DM" | "DO"
        | "ET" | "GT" | "GU" | "HK" | "HN" | "ID" | "IL" | "IN" | "JM" | "JP" | "KE" | "KH"
        | "KR" | "LA" | "MH" | "MM" | "MO" | "MT" | "MX" | "MZ" | "NI" | "NP" | "PA" | "PE"
        | "PH" | "PK" | "PR" | "PT" | "PY" | "SA" | "SG" | "SV" | "TH" | "TT" | "TW" | "UM"
        | "US" | "VE" | "VI" | "WS" | "YE" | "ZA" | "ZW" => Weekday::Sun,
        _ => Weekday::Mon,
    })
}

/// What a region of English changes: the clock, the order of a date and its
/// separator.
pub(super) fn english_region(
    language: &str,
    region: Option<&str>,
) -> (Option<Clock>, Option<DateOrder>, Option<&'static str>) {
    if language != "en" {
        return (None, None, None);
    }
    match region {
        Some("CA") => (Some(Clock::H12), Some(DateOrder::Ymd), Some("-")),
        Some("AU" | "NZ" | "IN" | "PH" | "AE" | "SA" | "EG" | "PK" | "BD") => {
            (Some(Clock::H12), None, None)
        }
        _ => (None, None, None),
    }
}
