/// An agent: a model with instructions and tools, which are ordinary async
/// methods of the agent marked `#[tool]`. Implement it with
/// [`#[agent]`](macro@crate::agent) on the `impl Agent for X` block, and
/// register it with `m.agent::<X>()`.
///
/// ```ignore
/// #[agent]
/// impl Agent for DealsAssistant {
///     const NAME: &'static str = "deals-assistant";
///
///     fn instructions(&self, run: &AgentRun) -> String {
///         format!("You are the sales assistant, talking to {}.", run.user().name)
///     }
///
///     /// Finds the deals the user can see, by words in the title.
///     #[tool(read_only)]
///     async fn search_deals(&self, run: &AgentRun, args: SearchDeals) -> Result<Vec<DealResource>> {
///         // ...
///     }
/// }
/// ```
pub trait Agent: Injectable {
    /// A stable name: it labels logs and metrics and is stored with each
    /// conversation.
    const NAME: &'static str;

    /// The system prompt. It gets the run, so it can name the user and the
    /// date.
    fn instructions(&self, run: &AgentRun) -> String;

    /// The model, step limit and memory.
    fn options(&self) -> AgentOptions {
        AgentOptions::default()
    }

    /// The tools (generated by `#[agent]`).
    #[doc(hidden)]
    fn tool_specs() -> Vec<ToolSpec> {
        Vec::new()
    }

    /// Calls tool `name` (generated by `#[agent]`).
    #[doc(hidden)]
    fn dispatch<'a>(
        &'a self,
        name: &'a str,
        run: &'a AgentRun,
        arguments: Value,
    ) -> BoxFuture<'a, ToolOutcome> {
        let _ = (run, arguments);
        Box::pin(async move { ToolOutcome::unknown(name) })
    }
}

/// Whether a run stores its conversation.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub enum Memory {
    /// Store messages and tool calls; a later run with the same
    /// conversation continues where it stopped.
    #[default]
    Conversation,
    /// Answer one message at a time; store nothing.
    None,
}

/// An agent's defaults ([`Agent::options`]).
#[derive(Clone, Debug, PartialEq)]
pub struct AgentOptions {
    /// The model name from `ai.models` (default `ai.default`).
    pub model: Option<String>,
    /// Model calls per run, tool rounds included (default 10).
    pub max_steps: usize,
    /// The output limit of each model call (default: the model's).
    pub max_tokens: Option<u32>,
    /// The sampling temperature (default: the model's).
    pub temperature: Option<f32>,
    /// Conversation memory (default on).
    pub memory: Memory,
    /// Run a step's read-only tool calls at the same time (default true).
    pub parallel_tools: bool,
    /// The time limit of one tool call, in seconds (default 30).
    pub tool_timeout_secs: u64,
}

impl Default for AgentOptions {
    fn default() -> Self {
        Self {
            model: None,
            max_steps: 10,
            max_tokens: None,
            temperature: None,
            memory: Memory::Conversation,
            parallel_tools: true,
            tool_timeout_secs: 30,
        }
    }
}

/// Who may use a tool, from its access attribute.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum ToolAccess {
    /// `#[can(Action, Subject)]`: the user may do the action on some
    /// records of the subject.
    Can {
        /// The action (`create`).
        action: &'static str,
        /// The subject type (`Activity`).
        subject: &'static str,
    },
    /// `#[permissions("deals.manage", ..)]`: every permission, without
    /// conditions.
    Permissions(Vec<&'static str>),
    /// `#[roles("admin", ..)]`: any of the roles.
    Roles(Vec<&'static str>),
}

impl ToolAccess {
    /// `#[can(action, subject)]`.
    pub fn can(action: &'static str, subject: &'static str) -> Self {
        ToolAccess::Can { action, subject }
    }

    /// `#[permissions(..)]`.
    pub fn permissions(permissions: &[&'static str]) -> Self {
        ToolAccess::Permissions(permissions.to_vec())
    }

    /// `#[roles(..)]`.
    pub fn roles(roles: &[&'static str]) -> Self {
        ToolAccess::Roles(roles.to_vec())
    }

    /// Whether `access` passes, with the same rules as a route's access
    /// attribute (`prefixes` maps permission prefixes to subjects).
    pub fn allows(&self, access: &PrincipalAccess, prefixes: &BTreeMap<String, String>) -> bool {
        match self {
            ToolAccess::Can { action, subject } => access.ability.can(action, subject, None),
            ToolAccess::Roles(roles) => {
                access.super_admin || roles.iter().any(|role| access.has_role(role))
            }
            ToolAccess::Permissions(permissions) => permissions.iter().all(|permission| {
                let (prefix, action) = permission.rsplit_once('.').unwrap_or((permission, ""));
                let action = if action == "*" {
                    navree_access::MANAGE
                } else {
                    action
                };
                let subject = prefixes.get(prefix).map(String::as_str).unwrap_or(prefix);
                access.ability.has_unconditional(action, subject)
            }),
        }
    }
}

/// A tool, as `#[agent]` describes it.
#[derive(Clone, Debug, PartialEq)]
pub struct ToolSpec {
    /// The method name.
    pub name: &'static str,
    /// The doc comment: what the model chooses the tool by.
    pub description: String,
    /// The JSON Schema of the arguments.
    pub parameters: Value,
    /// `#[tool(read_only)]`: changes nothing.
    pub read_only: bool,
    /// `#[tool(needs_approval)]`: the user decides before it runs.
    pub needs_approval: bool,
    /// The access attributes; all must pass.
    pub access: Vec<ToolAccess>,
}

impl ToolSpec {
    /// A tool named `name`.
    pub fn new(name: &'static str, description: impl Into<String>, parameters: Value) -> Self {
        Self {
            name,
            description: description.into(),
            parameters,
            read_only: false,
            needs_approval: false,
            access: Vec::new(),
        }
    }

    /// Marks it read-only.
    pub fn read_only(mut self) -> Self {
        self.read_only = true;
        self
    }

    /// Marks it as needing approval.
    pub fn needs_approval(mut self) -> Self {
        self.needs_approval = true;
        self
    }

    /// Adds an access requirement.
    pub fn access(mut self, access: ToolAccess) -> Self {
        self.access.push(access);
        self
    }

    /// Whether `access` may use the tool.
    pub fn allows(&self, access: &PrincipalAccess, prefixes: &BTreeMap<String, String>) -> bool {
        self.access.iter().all(|rule| rule.allows(access, prefixes))
    }
}

/// What a tool call returned (the `#[agent]` dispatch's result).
#[doc(hidden)]
pub enum ToolOutcome {
    /// The tool's result as JSON.
    Ok(Value),
    /// The tool's error.
    Err(AppError),
}

impl ToolOutcome {
    /// The outcome of calling a tool the agent doesn't have.
    pub fn unknown(name: &str) -> Self {
        ToolOutcome::Err(AppError::not_found().with_detail(format!("Unknown tool `{name}`")))
    }
}

/// Deserializes and validates `arguments` into `A`, then calls `f`
/// (generated dispatch).
#[doc(hidden)]
pub async fn call_tool<A, F, Fut, T, E>(arguments: Value, f: F) -> ToolOutcome
where
    A: DeserializeOwned + garde::Validate<Context = ()>,
    F: FnOnce(A) -> Fut,
    Fut: Future<Output = Result<T, E>>,
    T: Serialize,
    E: Into<AppError>,
{
    let arguments = if arguments.is_null() {
        Value::Object(Default::default())
    } else {
        arguments
    };
    let args = match navree_validation::validate_json::<A>(
        &arguments,
        &navree_validation::Messages::default(),
    ) {
        Ok(args) => args,
        Err(errors) => return ToolOutcome::Err(errors.into_app_error()),
    };
    outcome(f(args).await)
}

/// Calls a tool without arguments (generated dispatch).
#[doc(hidden)]
pub async fn call_tool_no_args<Fut, T, E>(future: Fut) -> ToolOutcome
where
    Fut: Future<Output = Result<T, E>>,
    T: Serialize,
    E: Into<AppError>,
{
    outcome(future.await)
}

fn outcome<T: Serialize, E: Into<AppError>>(result: Result<T, E>) -> ToolOutcome {
    match result {
        Ok(value) => match serde_json::to_value(value) {
            Ok(value) => ToolOutcome::Ok(value),
            Err(error) => ToolOutcome::Err(AppError::internal(format!(
                "the tool's result does not serialize: {error}"
            ))),
        },
        Err(error) => ToolOutcome::Err(error.into()),
    }
}

/// The JSON Schema of a tool's arguments type.
#[doc(hidden)]
pub fn tool_schema<A: utoipa::ToSchema>() -> Value {
    crate::schema::json_schema::<A>()
}

/// The JSON Schema of a tool without arguments.
#[doc(hidden)]
pub fn no_args_schema() -> Value {
    crate::schema::empty_object()
}

/// A tool call waiting for the user's approval.
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize, ToSchema)]
pub struct PendingApproval {
    /// The call id: approve or reject it by this id.
    pub call_id: String,
    /// The tool.
    pub tool: String,
    /// The arguments the model chose.
    pub arguments: Value,
}

/// One tool call of a run.
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize, ToSchema)]
pub struct AgentStep {
    /// The tool.
    pub tool: String,
    /// The arguments.
    pub arguments: Value,
    /// Whether it succeeded.
    pub ok: bool,
}

/// A finished run.
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize, ToSchema)]
pub struct AgentReply {
    /// The conversation, when the run has memory.
    pub conversation_id: Option<Uuid>,
    /// The model's answer.
    pub text: String,
    /// The tool calls made, in order.
    pub steps: Vec<AgentStep>,
    /// A call waiting for the user's decision.
    pub pending_approval: Option<PendingApproval>,
    /// The tokens of every model call of the run.
    pub usage: Usage,
}

#[cfg(test)]
mod tests {
    use std::sync::Arc;

    use navree_access::Rules;

    use super::*;

    fn access(roles: &[&str], rules: Rules) -> PrincipalAccess {
        PrincipalAccess {
            user: Some(Uuid::now_v7()),
            roles: roles.iter().map(|r| (*r).to_owned()).collect(),
            permissions: Vec::new(),
            version: 1,
            super_admin: false,
            ability: Arc::new(rules.build()),
        }
    }

    #[test]
    fn tool_access_follows_route_rules() {
        let mut rules = Rules::new();
        rules.can("create", "Activity");
        rules.can("manage", "Deal");
        let rep = access(&["rep"], rules);
        let prefixes: BTreeMap<String, String> = [("deals".to_owned(), "Deal".to_owned())].into();

        assert!(ToolAccess::can("create", "Activity").allows(&rep, &prefixes));
        assert!(!ToolAccess::can("delete", "Activity").allows(&rep, &prefixes));
        assert!(ToolAccess::roles(&["admin", "rep"]).allows(&rep, &prefixes));
        assert!(!ToolAccess::roles(&["admin"]).allows(&rep, &prefixes));
        assert!(ToolAccess::permissions(&["deals.*"]).allows(&rep, &prefixes));
        assert!(ToolAccess::permissions(&["deals.update"]).allows(&rep, &prefixes));
        assert!(!ToolAccess::permissions(&["users.read"]).allows(&rep, &prefixes));

        let tool = ToolSpec::new("reassign", "", no_args_schema())
            .needs_approval()
            .access(ToolAccess::can("manage", "Deal"))
            .access(ToolAccess::roles(&["manager"]));
        assert!(!tool.allows(&rep, &prefixes));
        assert!(tool.needs_approval && !tool.read_only);
    }

    #[derive(Debug, Deserialize, garde::Validate)]
    struct Args {
        #[garde(length(chars, min = 1))]
        subject: String,
    }

    #[tokio::test]
    async fn call_tool_validates_before_calling() {
        let outcome = call_tool(serde_json::json!({ "subject": "" }), |_: Args| async {
            panic!("not called");
            #[allow(unreachable_code)]
            Ok::<(), AppError>(())
        })
        .await;
        match outcome {
            ToolOutcome::Err(error) => {
                assert_eq!(error.status.as_u16(), 400);
                assert!(error.body()["errors"]["subject"].is_array());
            }
            ToolOutcome::Ok(_) => panic!("invalid arguments must not run the tool"),
        }
        let outcome =
            call_tool(
                serde_json::json!({ "subject": "Call Dana" }),
                |args: Args| async move {
                    Ok::<_, AppError>(serde_json::json!({ "logged": args.subject }))
                },
            )
            .await;
        assert!(matches!(outcome, ToolOutcome::Ok(value) if value["logged"] == "Call Dana"));
    }
}
